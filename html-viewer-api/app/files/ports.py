"""Interfaces the file use cases depend on. Azure adapters and test fakes implement them."""

from __future__ import annotations

from datetime import datetime
from typing import Iterable, Protocol

from .models import FileRecord


class FileRepository(Protocol):
    def get(self, owner_id: str, file_id: str) -> FileRecord | None: ...
    def save(self, record: FileRecord) -> None:
        """Writes unconditionally. For new files."""
        ...

    def update(self, record: FileRecord) -> bool:
        """Writes only if the stored file is still at `record.version`.

        False when someone else changed or deleted it since it was read: read again and retry.
        """
        ...

    def delete(self, owner_id: str, file_id: str) -> None: ...
    def list_ready(self, owner_id: str) -> list[FileRecord]: ...
    def list_pending_before(self, cutoff: datetime) -> Iterable[FileRecord]: ...


class SlugIndex(Protocol):
    """Which file a slug points to, per owner. `reserve` is the uniqueness check."""

    def reserve(self, owner_id: str, slug: str, file_id: str) -> bool: ...
    def release(self, owner_id: str, slug: str) -> None: ...
    def lookup(self, owner_id: str, slug: str) -> str | None: ...


class BlobStore(Protocol):
    def upload_url(self, blob_name: str, expires_at: datetime) -> str: ...
    def read_url(self, blob_name: str, expires_at: datetime, *, download_name: str | None = None) -> str: ...
    def get_size(self, blob_name: str) -> int | None: ...
    def finalize(self, blob_name: str) -> None: ...
    def delete(self, blob_name: str) -> None: ...
